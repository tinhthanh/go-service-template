// Command stubgen writes Unimplemented: a method for every operation of the
// generated StrictServerInterface, each answering problem.ErrNotBuilt (a 501
// the client reads as "unavailable"). internal/server embeds it below the
// features, so an operation a feature builds takes its place, and one the
// contract gains answers 501 until it is built.
//
//	go run ./tools/stubgen -in internal/api/api.gen.go -out internal/api/unimplemented.gen.go
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

const _interface = "StrictServerInterface"

var errNoInterface = errors.New("stubgen: no " + _interface + " in the file")

func main() {
	in := flag.String("in", "", "the generated server")
	out := flag.String("out", "", "the file to write")
	flag.Parse()

	src, err := stubs(*in)
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(*out, src, 0o600); err != nil {
		log.Fatal(err)
	}
}

// stubs reads the interface's methods and writes one stub for each, formatted.
func stubs(path string) ([]byte, error) {
	fset := token.NewFileSet()

	file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("stubgen: %w", err)
	}

	methods := interfaceMethods(file)
	if methods == nil {
		return nil, errNoInterface
	}

	var b bytes.Buffer

	b.WriteString("// Code generated by tools/stubgen. DO NOT EDIT.\n\npackage api\n\n")
	b.WriteString("import (\n\t\"context\"\n\n\t\"github.com/tinhthanh/go-service-template/internal/platform/problem\"\n)\n\n")
	b.WriteString("// Unimplemented answers every operation of the contract with problem.ErrNotBuilt.\n")
	b.WriteString("type Unimplemented struct{}\n\n")
	b.WriteString("var _ StrictServerInterface = Unimplemented{}\n")

	for _, m := range methods {
		fmt.Fprintf(&b, "\n// %s is not built yet.\nfunc (Unimplemented) %s(context.Context, %sRequestObject) (%sResponseObject, error) {\n\treturn nil, problem.ErrNotBuilt\n}\n", m, m, m, m)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("stubgen: format: %w", err)
	}

	return src, nil
}

func interfaceMethods(file *ast.File) []string {
	var names []string

	ast.Inspect(file, func(n ast.Node) bool {
		spec, ok := n.(*ast.TypeSpec)
		if !ok || spec.Name.Name != _interface {
			return true
		}

		iface, ok := spec.Type.(*ast.InterfaceType)
		if !ok {
			return false
		}

		names = []string{}

		for _, field := range iface.Methods.List {
			for _, name := range field.Names {
				names = append(names, name.Name)
			}
		}

		return false
	})

	return names
}

func TestHooks_OnlyTheCommandsThatMakeThemMayRewriteGeneratedCodeAndTheContract(t *testing.T) {
	t.Parallel()

	for command, maker := range map[string]bool{
		"make generate":                          true,
		"make contract-sync FROM=../app":         true,
		"go tool sqlc generate":                  true,
		"go run ./tools/stubgen":                 true,
		"sed -i '' 's/a/b/' internal/api/x.go":   false,
		"python3 - <<'EOF'\nopen('api/openapi')": false,
		"cat > internal/api/api.gen.go <<'EOF'":  false,
	} {
		assert.Equal(t, maker, _makers.MatchString(command), command)
	}
}

func TestHooks_TheContractAndGeneratedCodeAreRefusedAndTheRestIsNot(t *testing.T) {
	t.Chdir(t.TempDir())

	write := func(name, body string) {
		t.Helper()
		require.NoError(t, os.MkdirAll(filepath.Dir(name), 0o750))
		require.NoError(t, os.WriteFile(name, []byte(body), 0o600))
	}

	write("api/openapi.json", "{}")
	write("x.gen.go", "// Code generated by sqlc. DO NOT EDIT.\npackage x\n")
	write("x.go", "package x\n")

	assert.Contains(t, refused(filepath.Join("api", "openapi.json")), "client's contract")
	assert.Contains(t, refused("x.gen.go"), "is generated")
	assert.Empty(t, refused("x.go"))
}

func TestHooks_AShellCommandChecksOnlyWhatItChanged(t *testing.T) {
	t.Chdir(t.TempDir())

	_, ok := run("git", "init", "-q")
	require.True(t, ok)

	require.NoError(t, os.WriteFile(".gitignore", []byte("/.claude/bin/\n"), 0o600)) // as the repository's
	require.NoError(t, os.WriteFile("before.go", nil, 0o600))

	old := time.Now().Add(-time.Hour)
	require.NoError(t, os.Chtimes("before.go", old, old))
	require.NoError(t, os.Chtimes(".gitignore", old, old))

	markBash()
	require.NoError(t, os.WriteFile("after.go", nil, 0o600))

	assert.Equal(t, []string{"after.go"}, changedSince(_stamp))
}
